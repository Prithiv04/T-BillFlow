class AgentMandateRegistry(BaseContract):
    def __init__(self, address: str, w3: Web3):
        super().__init__(address, "AgentMandateRegistry", w3)

    def validate_mandate(
        self,
        mandate_id: str,
        agent: str,
        target: str,
        action: int,
        amount: int,
    ) -> None:
        """Call the view validateMandate(). Raises if invalid."""
        self.contract.functions.validateMandate(
            mandate_id, agent, target, action, amount
        ).call()

    def get_mandate(self, mandate_id: str) -> dict:
        """Fetch the full Mandate struct."""
        result = self.contract.functions.getMandate(mandate_id).call()
        return {
            "agent": result[0],
            "asset": result[1],
            "allowedTarget": result[2],
            "allowedActionsMask": result[3],
            "maxTx": result[4],
            "maxCumulative": result[5],
            "used": result[6],
            "validFrom": result[7],
            "validUntil": result[8],
            "nonce": result[9],
            "revoked": result[10],
        }

    def mandate_owner(self, mandate_id: str) -> str:
        return self.contract.functions.mandateOwner(mandate_id).call()


