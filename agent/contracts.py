# ─────────────────────────────────────────────────────────────────────────────
# Web3 factory
# ─────────────────────────────────────────────────────────────────────────────

def build_web3(rpc_url: str) -> Web3:
    """Create a Web3 instance. Applies PoA middleware if available (Arbitrum Sepolia)."""
    w3 = Web3(Web3.HTTPProvider(rpc_url, request_kwargs={"timeout": 30}))
    if HAS_POA_MW:
        try:
            w3.middleware_onion.inject(_poa_mw, layer=0)
        except Exception:
            pass  # web3.py v7+ auto-handles PoA
    return w3
